import { copyFile, mkdir, readFile, rm, writeFile } from 'node:fs/promises';
import { resolve, dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';
const root=resolve(dirname(fileURLToPath(import.meta.url)),'..');
const out=join(root,'www');
const pkg=JSON.parse(await readFile(join(root,'package.json'),'utf8'));
const parts=pkg.version.split('.').map(Number);
if(parts.length!==3||parts.some(x=>!Number.isInteger(x)||x<0)||parts[1]>=100||parts[2]>=1000)throw Error('Invalid TaskMate version');
const code=parts[0]*100000+parts[1]*1000+parts[2];
if(code>2100000000)throw Error('versionCode too high');
const assets=['index.html','app.js','app-update.js','styles.css','themes.css','config.js','excel-import.js','roster-data.js','sw.js','manifest.webmanifest','Template_Import_TaskMate_Jadwal_Rak.xlsx','icons/icon-192.png','icons/icon-512.png'];
await rm(out,{recursive:true,force:true});
for(const name of assets){const dest=join(out,name);await mkdir(dirname(dest),{recursive:true});await copyFile(join(root,name),dest);}
const indexPath=join(out,'index.html');
let html=await readFile(indexPath,'utf8');
const configTag='<script src="config.js"></script>';
if(!html.includes(configTag))throw Error('config.js tag missing');
html=html.replace(configTag,`<script>window.TASKMATE_NATIVE_APP=true;window.TASKMATE_NATIVE_VERSION_CODE=${code};window.TASKMATE_NATIVE_VERSION_NAME=${JSON.stringify(pkg.version)};document.documentElement.classList.add('taskmate-native');</script>\n ${configTag}`);
await writeFile(indexPath,html);
const appPath=join(out,'app.js');let app=await readFile(appPath,'utf8');
const sw="if('serviceWorker' in navigator && location.protocol!=='file:')navigator.serviceWorker.register('./sw.js').catch(()=>{});";
if(app.includes(sw))app=app.replace(sw,"if(!window.TASKMATE_NATIVE_APP && 'serviceWorker' in navigator && location.protocol!=='file:')navigator.serviceWorker.register('./sw.js').catch(()=>{});");
await writeFile(appPath,app);
const cssPath=join(out,'styles.css');await writeFile(cssPath,(await readFile(cssPath,'utf8'))+'\n@media(max-width:760px){html.taskmate-native .main{padding-top:max(16px,env(safe-area-inset-top))}}\n');
console.log(`TaskMate signed Android source prepared ${pkg.version}, code ${code}`);
